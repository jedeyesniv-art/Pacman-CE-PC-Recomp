r"""
gen_import_stubs.py - generate host\import_stubs.cpp from the recompiled function table.

Every Xbox import the generated code calls appears in ppc\ppc_func_mapping.cpp as
`{ 0x<thunk>, __imp__<Name> }`. This writes one weak logging stub per import, so the
host links and shows which imports the game actually calls. A real implementation
anywhere else in host\ (a normal, strong PPC_FUNC(__imp__<Name>)) replaces the stub.

Re-run after any recompile that changes the import list:
    python tools\gen_import_stubs.py
"""

import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
MAPPING = ROOT / "ppc" / "ppc_func_mapping.cpp"
OUTPUT = ROOT / "host" / "import_stubs.cpp"

# Imports that never return to the caller on real hardware. Their stubs log and stop the host.
FATAL = {
    "ExTerminateThread",
    "HalReturnToFirmware",
    "KeBugCheck",
    "KeBugCheckEx",
    "RtlRaiseException",
    "XamLoaderLaunchTitle",
    "XamLoaderTerminateTitle",
}


def main():
    text = MAPPING.read_text()
    names = sorted({n for n in re.findall(r"__imp__([A-Za-z0-9_]+) \}", text) if not n.startswith("sub_")})
    missing = FATAL - set(names)
    if missing:
        raise SystemExit(f"fatal stubs not in the import list: {sorted(missing)}")

    lines = [
        "// Generated by tools\\gen_import_stubs.py from ppc\\ppc_func_mapping.cpp - do not edit.",
        "// Weak logging stubs for every import; a strong PPC_FUNC(__imp__<Name>) elsewhere replaces one.",
        "",
        '#include "stubs.h"',
        "",
    ]
    for name in names:
        macro = "HOST_FATAL_STUB" if name in FATAL else "HOST_STUB"
        lines.append(f"{macro}({name})")
    lines.append("")

    OUTPUT.write_text("\n".join(lines))
    print(f"wrote {OUTPUT.relative_to(ROOT)}: {len(names)} stubs ({len(FATAL)} fatal)")


if __name__ == "__main__":
    main()
